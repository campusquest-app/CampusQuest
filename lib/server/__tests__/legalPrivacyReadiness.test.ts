import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { DEFAULT_POLICY_VERSION } from "@/lib/legal/policy";

function read(rel: string) {
  return readFileSync(join(process.cwd(), rel), "utf8");
}

describe("legal and App Store privacy readiness", () => {
  const privacy = read("app/legal/privacy/page.tsx");
  const consent = read("app/legal/data-consent/page.tsx");
  const terms = read("app/legal/terms/page.tsx");
  const support = read("app/support/page.tsx");
  const nextConfig = read("next.config.js");
  const plist = read("native/ios/App/App/Info.plist");
  const manifest = read("native/ios/App/App/PrivacyInfo.xcprivacy");
  const geo = read("lib/client/useUserGeolocation.ts");

  it("publishes the October 15, 2026 policy version without rewriting historical consents", () => {
    expect(DEFAULT_POLICY_VERSION).toBe("2026-10-15.1");
    expect(privacy).toContain("Effective Date: October 15, 2026");
    expect(read("supabase/migrations/20261015140000_legal_policy_version_2026_10_15.sql")).toContain(
      "2026-10-15.1",
    );
  });

  it("matches 1.0 product behavior in user-facing legal copy", () => {
    expect(privacy).not.toMatch(/QR scanning|QR scanner/i);
    expect(privacy).not.toMatch(/nearby quests|check-ins/i);
    expect(privacy).toContain("graduation year, major or academic area, interests, and communities");
    expect(privacy).toContain("We do not collect advertising identifiers such as IDFA");
    expect(privacy).toContain("We do not send your profile, messages, or location history to the university");
    expect(privacy).toContain("user-generated media we control");
    expect(privacy).not.toContain("Mapbox");
    expect(consent).toContain("They are not generated by a third-party AI model");
    expect(consent).not.toMatch(/AI-powered|Beta Service|artificial intelligence/i);
    expect(terms).toContain("Eligibility is a contractual requirement");
    expect(terms).toContain("We do not collect date of birth");
    expect(support).toContain("Campus memories attach to campus places, not your GPS location");
    expect(support).not.toMatch(/location-based memories/i);
  });

  it("keeps canonical legal routes and permanently redirects public aliases", () => {
    expect(nextConfig).toContain('source: "/privacy"');
    expect(nextConfig).toContain('destination: "/legal/privacy"');
    expect(nextConfig).toContain("permanent: true");
    expect(nextConfig).toContain('source: "/terms"');
    expect(nextConfig).toContain('destination: "/legal/terms"');
    expect(read("app/legal/privacy/page.tsx")).toContain("Privacy Policy");
    expect(read("app/legal/terms/page.tsx")).toContain("Terms");
  });

  it("declares when-in-use location only and keeps Realm usable without a fix", () => {
    expect(plist).toContain("NSLocationWhenInUseUsageDescription");
    expect(plist).not.toContain("NSLocationAlways");
    expect(plist).not.toContain("place campus events");
    expect(plist).toContain("show your position on The Realm map");
    expect(geo).toContain("you can still explore the map");
    expect(geo).not.toContain("alwaysAuthorization");
    expect(geo).not.toContain("CLLocationManager");
  });

  it("does not leave the disabled QR scanner as a reviewable destination", () => {
    const scan = read("app/scan/page.tsx");
    expect(scan).toContain("FEATURE_FLAGS.progression");
    expect(scan).toContain('router.replace("/")');
  });

  it("covers Device ID and in-app messages in the privacy manifest", () => {
    expect(manifest).toContain("<false/>");
    expect(manifest).toContain("NSPrivacyTracking");
    expect(manifest).toContain("NSPrivacyCollectedDataTypeDeviceID");
    expect(manifest).toContain("NSPrivacyCollectedDataTypeEmailsOrTextMessages");
    expect(manifest).toContain("NSPrivacyAccessedAPICategoryUserDefaults");
    expect(manifest).toContain("CA92.1");
    expect(manifest).toContain("NSPrivacyAccessedAPICategoryFileTimestamp");
    expect(manifest).toContain("C617.1");
  });
});
